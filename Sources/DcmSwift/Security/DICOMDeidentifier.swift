/// The options of the Basic Application Level Confidentiality Profile
/// (PS3.15 E.3), as columns of Table E.1-1.
public struct DICOMDeidentificationOptions: OptionSet, Hashable, Sendable {
    public let rawValue: Int
    public init(rawValue: Int) { self.rawValue = rawValue }

    /// Keeps the private attributes PS3.15 Table E.3.10-1 lists as safe.
    public static let retainSafePrivate = Self(rawValue: 1 << 0)
    public static let retainUIDs = Self(rawValue: 1 << 1)
    public static let retainDeviceIdentity = Self(rawValue: 1 << 2)
    public static let retainInstitutionIdentity = Self(rawValue: 1 << 3)
    public static let retainPatientCharacteristics = Self(rawValue: 1 << 4)
    /// Keeps dates and times unchanged.
    public static let retainLongitudinalFullDates = Self(rawValue: 1 << 5)
    /// Shifts dates by `DICOMDeidentifier.dateShift` days.
    public static let retainLongitudinalModifiedDates = Self(rawValue: 1 << 6)
    /// Keeps descriptions cleaned by `DICOMDeidentifier.cleaner`.
    public static let cleanDescriptors = Self(rawValue: 1 << 7)
    /// Keeps structured content cleaned by `DICOMDeidentifier.cleaner`.
    public static let cleanStructuredContent = Self(rawValue: 1 << 8)
    /// Keeps graphics and overlays cleaned by `DICOMDeidentifier.cleaner`.
    public static let cleanGraphics = Self(rawValue: 1 << 9)

    /// The options, with their key in the resource and their code in CID
    /// 7050, De-identification Method.
    static let all: [(option: Self, key: String, code: String)] = [
        (.retainSafePrivate, "retainSafePrivate", "113111"),
        (.retainUIDs, "retainUIDs", "113110"),
        (.retainDeviceIdentity, "retainDeviceIdentity", "113109"),
        (.retainInstitutionIdentity, "retainInstitutionIdentity", "113112"),
        (.retainPatientCharacteristics, "retainPatientCharacteristics", "113108"),
        (.retainLongitudinalFullDates, "retainLongitudinalFullDates", "113106"),
        (.retainLongitudinalModifiedDates, "retainLongitudinalModifiedDates", "113107"),
        (.cleanDescriptors, "cleanDescriptors", "113105"),
        (.cleanStructuredContent, "cleanStructuredContent", "113104"),
        (.cleanGraphics, "cleanGraphics", "113103"),
    ]
}

/// An action of PS3.15 Table E.1-1.
public enum DICOMDeidentificationAction: String, Sendable {
    /// Replace with a non-zero length dummy value.
    case dummy = "D"
    /// Replace with a zero length value.
    case zero = "Z"
    /// Remove.
    case remove = "X"
    /// Keep.
    case keep = "K"
    /// Clean: replace with values of similar meaning without identifying
    /// information.
    case clean = "C"
    /// Replace UIDs, consistently within the de-identified set.
    case replaceUID = "U"
    case zeroOrDummy = "Z/D"
    case removeOrZero = "X/Z"
    case removeOrDummy = "X/D"
    case removeOrZeroOrDummy = "X/Z/D"
    case removeOrZeroOrReplaceUIDs = "X/Z/U*"
}

/// PS3.15 Tables E.1-1 and E.3.10-1 for 2026d, generated by
/// Scripts/generate-dicom-deidentification.py.
public final class DICOMDeidentificationProfile: @unchecked Sendable {
    public struct Rule: Sendable {
        /// The tag as 8 uppercase hexadecimal digits, "X" standing for any
        /// digit, or "private" for every private attribute.
        public let tag: String
        public let name: String
        public let isRetired: Bool
        public let basic: DICOMDeidentificationAction
        /// The action of each option that changes the Basic Profile's.
        public let options: [String: DICOMDeidentificationAction]
    }

    /// A private attribute of Table E.3.10-1.
    public struct SafePrivateAttribute: Sendable {
        public let group: String
        /// The element number within its private block, such as "09" for
        /// (7053,xx09).
        public let element: String
        public let creator: String
    }

    public static let shared: DICOMDeidentificationProfile = {
        do {
            guard let url = Bundle.module.url(forResource: "dicom-deidentification-2026d", withExtension: "json") else {
                throw DICOMDeidentificationError("the de-identification resource is missing")
            }
            return try DICOMDeidentificationProfile(data: Data(contentsOf: url))
        } catch {
            fatalError("DcmSwift's bundled de-identification profile cannot be read: \(error)")
        }
    }()

    public let edition: String
    public let rules: [Rule]
    public let safePrivateAttributes: [SafePrivateAttribute]
    private let exact: [String: Rule]
    private let patterns: [Rule]
    let privateRule: Rule?

    public init(data: Data) throws {
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
            throw DICOMDeidentificationError("the de-identification profile is not a JSON object")
        }
        edition = root["edition"] as? String ?? ""
        rules = try (root["attributes"] as? [[String: Any]] ?? []).map { entry in
            guard let tag = entry["tag"] as? String, let basic = (entry["basic"] as? String).flatMap(DICOMDeidentificationAction.init) else {
                throw DICOMDeidentificationError("invalid attribute \(entry)")
            }
            var options: [String: DICOMDeidentificationAction] = [:]
            for (key, value) in entry["options"] as? [String: String] ?? [:] {
                guard let action = DICOMDeidentificationAction(rawValue: value) else {
                    throw DICOMDeidentificationError("invalid action \(value) of \(tag)")
                }
                options[key] = action
            }
            return Rule(tag: tag, name: entry["name"] as? String ?? "", isRetired: entry["retired"] as? Bool ?? false,
                        basic: basic, options: options)
        }
        safePrivateAttributes = (root["safePrivate"] as? [[String: String]] ?? []).compactMap { entry in
            guard let tag = entry["tag"], tag.count == 8, let creator = entry["creator"] else { return nil }
            return SafePrivateAttribute(group: String(tag.prefix(4)), element: String(tag.suffix(2)),
                                        creator: Self.normalized(creator))
        }
        exact = Dictionary(rules.filter { !$0.tag.contains("X") && $0.tag != "private" }.map { ($0.tag, $0) },
                           uniquingKeysWith: { first, _ in first })
        patterns = rules.filter { $0.tag.contains("X") }
        privateRule = rules.first { $0.tag == "private" }
    }

    /// The rule of a standard attribute, by its tag as 8 hexadecimal digits.
    public func rule(for tag: String) -> Rule? {
        let tag = tag.uppercased()
        if let rule = exact[tag] { return rule }
        return patterns.first { rule in zip(rule.tag, tag).allSatisfy { $0 == "X" || $0 == $1 } }
    }

    /// Whether a private attribute is safe, by its group, the element number
    /// within its block, and its Private Creator.
    public func isSafePrivate(group: String, element: String, creator: String) -> Bool {
        let creator = Self.normalized(creator)
        return safePrivateAttributes.contains {
            $0.group == group.uppercased() && $0.element == element.uppercased() && $0.creator == creator
        }
    }

    static func normalized(_ creator: String) -> String {
        creator.trimmingCharacters(in: CharacterSet(charactersIn: " \0")).uppercased()
    }
}

public struct DICOMDeidentificationError: Error, CustomStringConvertible {
    public let description: String
    init(_ description: String) { self.description = description }
}

/// What the de-identifier did to a data set.
public struct DICOMDeidentificationReport: Sendable {
    public struct Change: Sendable, Equatable {
        /// The tags from the top-level attribute to the attribute.
        public let path: [String]
        /// The action applied: D, Z, X, K, C, or U.
        public let action: DICOMDeidentificationAction
    }

    public internal(set) var changes: [Change] = []

    public func count(of action: DICOMDeidentificationAction) -> Int {
        changes.filter { $0.action == action }.count
    }
}

/// De-identifies data sets with the Basic Application Level Confidentiality
/// Profile of PS3.15 Annex E and its options.
///
/// Every attribute of Table E.1-1 is protected wherever it appears, in
/// Sequence Items too. Compound actions such as X/Z/D follow the Type of the
/// attribute in the IOD of the SOP Class (PS3.3): D for Type 1, Z for Type 2,
/// X otherwise. Private attributes are removed, except the safe ones of
/// Table E.3.10-1 with `retainSafePrivate`. UIDs are replaced by UIDs derived
/// from `key`, so that the instances of a study de-identified with the same
/// key stay consistent. Patient Identity Removed (0012,0062), De-identification
/// Method (0012,0063), and De-identification Method Code Sequence (0012,0064)
/// record the profile and options.
///
/// When several options give an action to an attribute, the one that keeps
/// more wins: K, then C. A C action needs `cleaner`, except for the dates of
/// `retainLongitudinalModifiedDates`, which are shifted; without a cleaner,
/// the Basic Profile's action applies. Pixel Data is not inspected: the Clean
/// Pixel Data and Clean Recognizable Visual Features Options are not claimed.
public struct DICOMDeidentifier: Sendable {
    public let options: DICOMDeidentificationOptions
    /// The secret from which replacement UIDs, and the default date shift,
    /// are derived.
    public let key: Data
    /// Days added to dates with `retainLongitudinalModifiedDates`.
    public var dateShift: Int
    /// Cleans an attribute in place for a C action; returns false to leave
    /// it to the Basic Profile's action.
    public var cleaner: (@Sendable (DataElement) -> Bool)?
    public let profile: DICOMDeidentificationProfile
    public let specification: DICOMIODSpecification

    /// The dummy text of D actions.
    public static let dummyText = "ANONYMIZED"

    public init(options: DICOMDeidentificationOptions = [], key: Data? = nil, dateShift: Int? = nil,
                profile: DICOMDeidentificationProfile = .shared,
                specification: DICOMIODSpecification = .shared) throws {
        if options.contains(.retainLongitudinalFullDates) && options.contains(.retainLongitudinalModifiedDates) {
            throw DICOMDeidentificationError("full and modified dates are exclusive options")
        }
        self.options = options
        let key = key ?? SymmetricKey(size: .bits256).withUnsafeBytes { Data($0) }
        self.key = key
        let digest = Array(HMAC<SHA256>.authenticationCode(for: Data("date shift".utf8), using: SymmetricKey(data: key)))
        // Between one and ten years back, in days.
        self.dateShift = dateShift ?? -(365 + Int(UInt16(digest[0]) << 8 | UInt16(digest[1])) % 3285)
        self.profile = profile
        self.specification = specification
    }

    /// The UID that replaces `uid`: 2.25 followed by 128 bits of
    /// HMAC-SHA-256 of the UID under `key` (PS3.5 B.2).
    public func replacementUID(for uid: String) -> String {
        let trimmed = uid.trimmingCharacters(in: CharacterSet(charactersIn: " \0"))
        let code = HMAC<SHA256>.authenticationCode(for: Data(trimmed.utf8), using: SymmetricKey(data: key))
        return "2.25." + Self.decimal(Array(code.prefix(16)))
    }

    /// De-identifies a data set in place, its File Meta Information
    /// included.
    @discardableResult
    public func deidentify(_ dataSet: DataSet) -> DICOMDeidentificationReport {
        var report = DICOMDeidentificationReport()
        let sopClass = dataSet.string(forTag: "SOPClassUID") ?? ""
        let iod = specification.iod(forSOPClass: sopClass)
        let top = (iod?.modules ?? []).compactMap(\.table).flatMap { specification.tree($0) }
        let groups = (iod?.functionalGroups ?? []).compactMap(\.table).flatMap { specification.tree($0) }
        var level = Level(elements: dataSet.datasetElements, nodes: top, functionalGroups: groups)
        process(&level, path: [], report: &report)
        let kept = Set(level.elements.map { ObjectIdentifier($0) })
        for element in dataSet.datasetElements where !kept.contains(ObjectIdentifier(element)) {
            _ = dataSet.remove(dataElement: element)
        }
        record(in: dataSet)
        rewriteMetaInformation(of: dataSet)
        return report
    }

    // MARK: Attributes

    /// The elements of a data set or an Item, with the IOD attributes that
    /// may appear there.
    private struct Level {
        var elements: [DataElement]
        let nodes: [DICOMIODSpecification.Node]
        let functionalGroups: [DICOMIODSpecification.Node]
    }

    private func process(_ level: inout Level, path: [String], report: inout DICOMDeidentificationReport) {
        var kept: [DataElement] = []
        let creators = privateCreators(level.elements)
        for element in level.elements {
            let tag = element.tagCode().uppercased()
            let group = String(tag.prefix(4))
            // A standard attribute written as UN is read with its VR in the
            // Data Dictionary; UN Values are Little Endian (PS3.5 6.2.2).
            if element.vr == .UN, !(element is DataSequence),
               let known = DicomSpec.shared.vrForTag(withCode: element.tagCode()), ![.UN, .SQ].contains(known) {
                element.vr = known
                element.byteOrder = .LittleEndian
            }
            let location = path + [tag]
            // Group lengths, retired, would no longer match; group 0004 is
            // for DICOMDIR only (PS3.15 E.1.1).
            if tag.hasSuffix("0000") || group == "0004" {
                report.changes.append(.init(path: location, action: .remove))
                continue
            }
            if let groupNumber = Int(group, radix: 16), groupNumber % 2 == 1 {
                if keepPrivate(element, tag: tag, creators: creators) {
                    kept.append(element)
                    report.changes.append(.init(path: location, action: .keep))
                } else {
                    report.changes.append(.init(path: location, action: .remove))
                }
                continue
            }
            let nodes = level.nodes.filter { $0.tag == tag }
            guard let rule = profile.rule(for: tag) else {
                // Not listed: kept, but its Items may hold listed attributes.
                recurse(element, tag: tag, nodes: nodes, level: level, path: location, report: &report)
                kept.append(element)
                continue
            }
            let action = resolve(rule, type: strongestType(nodes))
            if apply(action, rule: rule, to: element, nodes: nodes, level: level, path: location, report: &report) {
                kept.append(element)
            }
        }
        // Private Creators without a kept attribute of their block go.
        let keptBlocks = Set(kept.compactMap { element -> String? in
            let tag = element.tagCode().uppercased()
            guard let group = Int(tag.prefix(4), radix: 16), group % 2 == 1,
                  let number = Int(tag.suffix(4), radix: 16), number > 0x00FF else { return nil }
            return String(tag.prefix(4)) + String(tag.dropFirst(4).prefix(2))
        })
        level.elements = kept.filter { element in
            let tag = element.tagCode().uppercased()
            guard let group = Int(tag.prefix(4), radix: 16), group % 2 == 1,
                  let number = Int(tag.suffix(4), radix: 16), (0x0010...0x00FF).contains(number) else { return true }
            return keptBlocks.contains(String(tag.prefix(4)) + String(tag.suffix(2)))
        }
    }

    /// Applies an action; returns false when the element is removed.
    private func apply(_ action: DICOMDeidentificationAction, rule: DICOMDeidentificationProfile.Rule,
                       to element: DataElement, nodes: [DICOMIODSpecification.Node], level: Level,
                       path: [String], report: inout DICOMDeidentificationReport) -> Bool {
        switch action {
        case .remove:
            report.changes.append(.init(path: path, action: .remove))
            return false
        case .keep:
            report.changes.append(.init(path: path, action: .keep))
            return true
        case .zero:
            makeEmpty(element)
            report.changes.append(.init(path: path, action: .zero))
            return true
        case .dummy:
            if element is DataSequence {
                recurse(element, tag: rule.tag, nodes: nodes, level: level, path: path, report: &report)
            } else {
                setDummy(element)
            }
            report.changes.append(.init(path: path, action: .dummy))
            return true
        case .replaceUID:
            if element is DataSequence {
                recurse(element, tag: rule.tag, nodes: nodes, level: level, path: path, report: &report)
            } else if element.vr == .UI {
                let values = (element.textValues ?? []).map(replacementUID)
                _ = element.setTextValues(values)
            } else {
                setDummy(element)
            }
            report.changes.append(.init(path: path, action: .replaceUID))
            return true
        case .clean:
            if options.contains(.retainLongitudinalModifiedDates), [.DA, .DT].contains(element.vr),
               rule.options["retainLongitudinalModifiedDates"] == .clean {
                shiftDates(element)
                report.changes.append(.init(path: path, action: .clean))
                return true
            }
            if let cleaner, cleaner(element) {
                report.changes.append(.init(path: path, action: .clean))
                return true
            }
            if [.TM].contains(element.vr), options.contains(.retainLongitudinalModifiedDates),
               rule.options["retainLongitudinalModifiedDates"] == .clean {
                // Times keep their value when dates are shifted.
                report.changes.append(.init(path: path, action: .keep))
                return true
            }
            let basic = resolve(rule.basic, type: strongestType(nodes))
            return apply(basic, rule: rule, to: element, nodes: nodes, level: level, path: path, report: &report)
        case .zeroOrDummy, .removeOrZero, .removeOrDummy, .removeOrZeroOrDummy, .removeOrZeroOrReplaceUIDs:
            let resolved = resolve(action, type: strongestType(nodes))
            return apply(resolved, rule: rule, to: element, nodes: nodes, level: level, path: path, report: &report)
        }
    }

    /// The action for the selected options: K if one keeps the attribute,
    /// else C if one cleans it, else the Basic Profile's.
    private func resolve(_ rule: DICOMDeidentificationProfile.Rule, type: String?) -> DICOMDeidentificationAction {
        let selected = DICOMDeidentificationOptions.all.filter { options.contains($0.option) }
            .compactMap { rule.options[$0.key] }
        if selected.contains(.keep) { return .keep }
        if selected.contains(.clean) { return .clean }
        return rule.basic
    }

    /// A compound action for an attribute of `type` in the IOD: Type 1
    /// needs a value, Type 2 may be empty, others may go (PS3.15 Table
    /// E.1-1 notes).
    private func resolve(_ action: DICOMDeidentificationAction, type: String?) -> DICOMDeidentificationAction {
        let required = type == "1" || type == "1C"
        let present = required || type == "2" || type == "2C"
        switch action {
        case .zeroOrDummy: return required ? .dummy : .zero
        case .removeOrZero: return present ? .zero : .remove
        case .removeOrDummy: return present ? .dummy : .remove
        case .removeOrZeroOrDummy: return required ? .dummy : present ? .zero : .remove
        case .removeOrZeroOrReplaceUIDs: return required ? .replaceUID : present ? .zero : .remove
        default: return action
        }
    }

    private func strongestType(_ nodes: [DICOMIODSpecification.Node]) -> String? {
        let order = ["1", "1C", "2", "2C", "3"]
        return nodes.map(\.type).min { (order.firstIndex(of: $0) ?? 9) < (order.firstIndex(of: $1) ?? 9) }
    }

    private func recurse(_ element: DataElement, tag: String, nodes: [DICOMIODSpecification.Node], level: Level,
                         path: [String], report: inout DICOMDeidentificationReport) {
        guard let sequence = element as? DataSequence, !(element is PixelSequence) else { return }
        // Functional Group Sequences hold the IOD's Functional Group Macros.
        let children = tag == "52009229" || tag == "52009230" ? level.functionalGroups : nodes.flatMap(\.children)
        for item in sequence.items {
            var inner = Level(elements: item.elements, nodes: children, functionalGroups: level.functionalGroups)
            process(&inner, path: path, report: &report)
            item.elements = inner.elements
        }
    }

    // MARK: Values

    private func makeEmpty(_ element: DataElement) {
        if let sequence = element as? DataSequence {
            sequence.items = []
        } else {
            element.data = Data()
            element.length = 0
        }
        element.recalculateLengthsOfParents()
    }

    private func setDummy(_ element: DataElement) {
        let text: String?
        switch element.vr {
        case .AE, .CS, .LO, .SH, .PN, .LT, .ST, .UT, .UC: text = Self.dummyText
        case .DA: text = "19000101"
        case .TM: text = "000000"
        case .DT: text = "19000101000000"
        case .AS: text = "000Y"
        case .DS, .IS: text = "0"
        case .UI: text = replacementUID(for: element.textValues?.first ?? "")
        case .UR: text = "urn:anonymized"
        default: text = nil
        }
        if let text {
            _ = element.setValue(text)
            return
        }
        let width: Int
        switch element.vr {
        case .US, .SS: width = 2
        case .UL, .SL, .FL, .AT: width = 4
        case .FD, .SV, .UV: width = 8
        default: width = 2
        }
        element.data = Data(count: width)
        element.length = width
        element.recalculateLengthsOfParents()
    }

    private func shiftDates(_ element: DataElement) {
        guard let values = element.textValues else { return }
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "UTC")!
        let formatter = DateFormatter()
        formatter.calendar = calendar
        formatter.timeZone = calendar.timeZone
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "yyyyMMdd"
        let shifted = values.map { value -> String in
            guard value.count >= 8, let date = formatter.date(from: String(value.prefix(8))),
                  let moved = calendar.date(byAdding: .day, value: dateShift, to: date) else { return value }
            return formatter.string(from: moved) + value.dropFirst(8)
        }
        _ = element.setTextValues(shifted)
    }

    // MARK: Private attributes

    /// The Private Creator of each block, by group and block, such as
    /// "0019" + "10".
    private func privateCreators(_ elements: [DataElement]) -> [String: String] {
        var creators: [String: String] = [:]
        for element in elements {
            let tag = element.tagCode().uppercased()
            guard let group = Int(tag.prefix(4), radix: 16), group % 2 == 1,
                  let number = Int(tag.suffix(4), radix: 16), (0x0010...0x00FF).contains(number) else { continue }
            creators[String(tag.prefix(4)) + String(tag.suffix(2))] = element.textValues?.first ?? ""
        }
        return creators
    }

    private func keepPrivate(_ element: DataElement, tag: String, creators: [String: String]) -> Bool {
        guard options.contains(.retainSafePrivate),
              let number = Int(tag.suffix(4), radix: 16) else { return false }
        // Private Creators are kept with their block, decided afterwards.
        if (0x0010...0x00FF).contains(number) { return true }
        guard number > 0x00FF else { return false }
        let group = String(tag.prefix(4))
        let block = String(tag.dropFirst(4).prefix(2))
        guard let creator = creators[group + block] else { return false }
        return profile.isSafePrivate(group: group, element: String(tag.suffix(2)), creator: creator)
    }

    // MARK: Recording the method (PS3.15 E.1.1)

    private func record(in dataSet: DataSet) {
        _ = dataSet.set(value: "YES", forTagName: "PatientIdentityRemoved")
        var methods = ["DcmSwift PS3.15 \(profile.edition) Basic Profile"]
        var codes = ["113100"]
        for entry in DICOMDeidentificationOptions.all where options.contains(entry.option) {
            methods.append(entry.key)
            codes.append(entry.code)
        }
        _ = dataSet.set(textValues: methods, forTagName: "DeidentificationMethod")
        if let existing = dataSet.element(forTagName: "DeidentificationMethodCodeSequence") {
            _ = dataSet.remove(dataElement: existing)
        }
        if let tag = DicomSpec.shared.dataTag(forName: "DeidentificationMethodCodeSequence") {
            let sequence = DataSequence(withTag: tag)
            sequence.vr = .SQ
            sequence.length = -1
            for code in codes {
                let item = DataItem(withTag: DataTag(withGroup: "fffe", element: "e000"), parent: sequence)
                item.length = -1
                let meaning = DICOMTerminology.shared.dicomCode(code)?.meaning ?? ""
                for (name, value) in [("CodeValue", code), ("CodingSchemeDesignator", "DCM"), ("CodeMeaning", meaning)] {
                    guard let element = DataElement(withTagName: name, dataset: dataSet, parent: item) else { continue }
                    _ = element.setValue(value)
                    item.elements.append(element)
                }
                sequence.items.append(item)
            }
            dataSet.add(element: sequence)
        }
        let temporal = options.contains(.retainLongitudinalFullDates) ? "UNMODIFIED"
            : options.contains(.retainLongitudinalModifiedDates) ? "MODIFIED" : "REMOVED"
        _ = dataSet.set(value: temporal, forTagName: "LongitudinalTemporalInformationModified")
        dataSet.sortElements()
    }

    /// Replaces the File Meta Information with a description of DcmSwift,
    /// keeping the Transfer Syntax (PS3.15 E.1.1).
    private func rewriteMetaInformation(of dataSet: DataSet) {
        guard !dataSet.metaInformationHeaderElements.isEmpty else { return }
        let keep: Set<String> = ["FileMetaInformationGroupLength", "FileMetaInformationVersion", "TransferSyntaxUID"]
        for element in dataSet.metaInformationHeaderElements where !keep.contains(element.name) {
            _ = dataSet.remove(dataElement: element)
        }
        if let sopClass = dataSet.string(forTag: "SOPClassUID") {
            _ = dataSet.set(value: sopClass, forTagName: "MediaStorageSOPClassUID")
        }
        if let sopInstance = dataSet.string(forTag: "SOPInstanceUID") {
            _ = dataSet.set(value: sopInstance, forTagName: "MediaStorageSOPInstanceUID")
        }
        _ = dataSet.set(value: DICOMImplementation.classUID, forTagName: "ImplementationClassUID")
        _ = dataSet.set(value: DICOMImplementation.versionName, forTagName: "ImplementationVersionName")
        dataSet.preamble = nil
        dataSet.sortElements()
        dataSet.recalculateFileMetaInformationGroupLength()
    }

    // MARK: Numbers

    /// The decimal digits of a big-endian unsigned number.
    static func decimal(_ bytes: [UInt8]) -> String {
        var number = bytes
        var digits: [Character] = []
        while number.contains(where: { $0 != 0 }) {
            var remainder = 0
            for index in number.indices {
                let value = remainder << 8 | Int(number[index])
                number[index] = UInt8(value / 10)
                remainder = value % 10
            }
            digits.append(Character(String(remainder)))
        }
        return digits.isEmpty ? "0" : String(digits.reversed())
    }
