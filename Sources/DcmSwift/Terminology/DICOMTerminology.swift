import Foundation

/// A coded concept: a Code Value in a Coding Scheme, with its Code Meaning
/// (PS3.3 8.8, Code Sequence Macro).
public struct DICOMCode: Hashable, Sendable, CustomStringConvertible {
    /// Coding Scheme Designator (0008,0102), such as SCT, DCM, or LN.
    public var scheme: String
    /// Code Value (0008,0100), Long Code Value (0008,0119), or URN Code
    /// Value (0008,0120).
    public var value: String
    /// Code Meaning (0008,0104).
    public var meaning: String
    /// Coding Scheme Version (0008,0103), when the scheme requires it.
    public var schemeVersion: String?

    public init(_ value: String, scheme: String, meaning: String, schemeVersion: String? = nil) {
        self.scheme = scheme
        self.value = value
        self.meaning = meaning
        self.schemeVersion = schemeVersion
    }

    /// Reads the Basic Code Sequence Macro attributes of an item.
    public init?(item: DataItem) {
        func string(_ keyword: String) -> String? {
            guard let value = item.element(withName: keyword)?.value as? String else { return nil }
            let trimmed = value.trimmingCharacters(in: CharacterSet(charactersIn: " \0"))
            return trimmed.isEmpty ? nil : trimmed
        }
        guard let value = string("CodeValue") ?? string("LongCodeValue") ?? string("URNCodeValue"),
              let scheme = string("CodingSchemeDesignator") ?? (string("URNCodeValue") != nil ? "" : nil) else {
            return nil
        }
        self.init(value, scheme: scheme, meaning: string("CodeMeaning") ?? "",
                  schemeVersion: string("CodingSchemeVersion"))
    }

    /// Two codes denote the same concept when their scheme and value match;
    /// Code Meanings vary between groups and languages (PS3.16 8.1).
    public func sameConcept(as other: DICOMCode) -> Bool {
        scheme == other.scheme && value == other.value
    }

    public var description: String { "(\(value), \(scheme), \"\(meaning)\")" }
}

/// A Coding Scheme of PS3.16 Table 8-1.
public struct DICOMCodingScheme: Hashable, Sendable {
    public let designator: String
    public let uid: String?
    public let name: String?
    public let organization: String?
}

/// A Context Group of PS3.16 Annex B: the codes allowed in a context.
public struct DICOMContextGroup: Sendable {
    /// The Context Group ID, such as 4031.
    public let cid: Int
    public let name: String
    public let keyword: String?
    /// Whether codes outside the group may be used (PS3.16 7.2.1.1). Nil
    /// when PS3.16 does not say.
    public let isExtensible: Bool?
    /// The Context Group Version (0008,0106), such as 20250401.
    public let version: String?
    /// The Context UID (0008,0117) that identifies the group.
    public let uid: String?
    /// The codes listed in the group itself, in the order of PS3.16.
    public let codes: [DICOMCode]
    /// The groups it includes.
    public let includedGroups: [Int]
    /// The rule that defines a group without a list of codes, such as all
    /// LOINC document names.
    public let definition: String?
}

/// The DICOM Content Mapping Resource (PS3.16 2026d): Coding Schemes, DICOM
/// Controlled Terminology, and Context Groups, generated by
/// Scripts/generate-dicom-terminology.py.
public final class DICOMTerminology: @unchecked Sendable {
    /// The terminology bundled with DcmSwift, loaded on first use.
    public static let shared: DICOMTerminology = {
        do {
            guard let url = Bundle.module.url(forResource: "dicom-terminology-2026d", withExtension: "json") else {
                throw DICOMTerminologyError("the terminology resource is missing")
            }
            return try DICOMTerminology(data: Data(contentsOf: url))
        } catch {
            fatalError("DcmSwift's bundled terminology cannot be read: \(error)")
        }
    }()

    /// The edition of the Standard, such as 2026d.
    public let edition: String
    private let schemes: [String: DICOMCodingScheme]
    private let schemesByUID: [String: DICOMCodingScheme]
    private let dicomCodes: [String: (meaning: String, retired: Bool)]
    private let groups: [Int: DICOMContextGroup]
    private let groupsByKeyword: [String: Int]
    private let groupsByUID: [String: Int]

    public struct DICOMTerminologyError: Error, CustomStringConvertible {
        public let description: String
        init(_ description: String) { self.description = description }
    }

    /// Reads a terminology resource in the format of the generator.
    public init(data: Data) throws {
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
            throw DICOMTerminologyError("the terminology is not a JSON object")
        }
        edition = root["edition"] as? String ?? ""
        var schemes: [String: DICOMCodingScheme] = [:], byUID: [String: DICOMCodingScheme] = [:]
        for entry in root["codingSchemes"] as? [[String: String]] ?? [] {
            guard let designator = entry["designator"] else { continue }
            let scheme = DICOMCodingScheme(designator: designator, uid: entry["uid"], name: entry["name"],
                                           organization: entry["organization"])
            schemes[designator] = scheme
            if let uid = scheme.uid { byUID[uid] = scheme }
        }
        self.schemes = schemes
        schemesByUID = byUID
        var dicomCodes: [String: (String, Bool)] = [:]
        for entry in root["dicomCodes"] as? [[Any]] ?? [] {
            guard entry.count >= 2, let value = entry[0] as? String, let meaning = entry[1] as? String else { continue }
            dicomCodes[value] = (meaning, entry.count > 2)
        }
        self.dicomCodes = dicomCodes
        var groups: [Int: DICOMContextGroup] = [:], byKeyword: [String: Int] = [:], groupsByUID: [String: Int] = [:]
        for entry in root["contextGroups"] as? [[String: Any]] ?? [] {
            guard let cid = entry["cid"] as? Int else { continue }
            let codes = (entry["codes"] as? [[String]] ?? []).compactMap { row -> DICOMCode? in
                guard row.count >= 3 else { return nil }
                return DICOMCode(row[1], scheme: row[0], meaning: row[2], schemeVersion: row.count > 3 ? row[3] : nil)
            }
            let group = DICOMContextGroup(
                cid: cid, name: entry["name"] as? String ?? "", keyword: entry["keyword"] as? String,
                isExtensible: entry["extensible"] as? Bool, version: entry["version"] as? String,
                uid: entry["uid"] as? String, codes: codes, includedGroups: entry["includes"] as? [Int] ?? [],
                definition: entry["definition"] as? String)
            groups[cid] = group
            if let keyword = group.keyword { byKeyword[keyword] = cid }
            if let uid = group.uid { groupsByUID[uid] = cid }
        }
        self.groups = groups
        groupsByKeyword = byKeyword
        self.groupsByUID = groupsByUID
    }

    // MARK: Coding Schemes

    public func codingScheme(_ designator: String) -> DICOMCodingScheme? { schemes[designator] }
    public func codingScheme(uid: String) -> DICOMCodingScheme? { schemesByUID[uid] }
    public var codingSchemes: [DICOMCodingScheme] { schemes.values.sorted { $0.designator < $1.designator } }

    // MARK: DICOM Controlled Terminology (PS3.16 Annex D)

    /// A code of the DCM scheme, by Code Value.
    public func dicomCode(_ value: String) -> DICOMCode? {
        dicomCodes[value].map { DICOMCode(value, scheme: "DCM", meaning: $0.meaning) }
    }

    /// Whether a DCM code is retired.
    public func isRetiredDICOMCode(_ value: String) -> Bool { dicomCodes[value]?.retired ?? false }

    // MARK: Context Groups (PS3.16 Annex B)

    public func contextGroup(_ cid: Int) -> DICOMContextGroup? { groups[cid] }
    public func contextGroup(keyword: String) -> DICOMContextGroup? { groupsByKeyword[keyword].flatMap { groups[$0] } }
    public func contextGroup(uid: String) -> DICOMContextGroup? { groupsByUID[uid].flatMap { groups[$0] } }
    public var contextGroupIDs: [Int] { groups.keys.sorted() }

    /// The codes of a group and of the groups it includes, transitively,
    /// each concept once, in the order of PS3.16.
    public func codes(in cid: Int) -> [DICOMCode] {
        var result: [DICOMCode] = [], seenGroups = Set<Int>(), seenConcepts = Set<String>()
        func visit(_ cid: Int) {
            guard seenGroups.insert(cid).inserted, let group = groups[cid] else { return }
            for code in group.codes where seenConcepts.insert(code.scheme + "\u{1}" + code.value).inserted {
                result.append(code)
            }
            group.includedGroups.forEach(visit)
        }
        visit(cid)
        return result
    }

    /// How a code relates to a Context Group.
    public enum Membership: Equatable, Sendable {
        /// The group, or a group it includes, lists the code.
        case member
        /// The group does not list it but is extensible, so the code may
        /// still be used.
        case allowedByExtension
        /// The group does not list it and is not extensible.
        case notAllowed
        /// The group is defined by a rule, or unknown, so membership cannot
        /// be decided from the lists.
        case undetermined
    }

    /// Whether `code` belongs to group `cid`, by scheme and value.
    public func membership(of code: DICOMCode, in cid: Int) -> Membership {
        guard let group = groups[cid] else { return .undetermined }
        if codes(in: cid).contains(where: { $0.sameConcept(as: code) }) { return .member }
        if group.codes.isEmpty && group.includedGroups.isEmpty { return .undetermined }
        switch group.isExtensible {
        case true?: return .allowedByExtension
        case false?: return .notAllowed
        case nil: return .undetermined
        }
    }

    /// The Code Meaning PS3.16 gives a code: in the group when given, else
    /// in the DCM definitions, else in the first group that lists it.
    public func meaning(of code: DICOMCode, in cid: Int? = nil) -> String? {
        if let cid, let match = codes(in: cid).first(where: { $0.sameConcept(as: code) }) { return match.meaning }
        if code.scheme == "DCM", let dicom = dicomCodes[code.value] { return dicom.meaning }
        for id in contextGroupIDs {
            if let match = groups[id]?.codes.first(where: { $0.sameConcept(as: code) }) { return match.meaning }
        }
        return nil
    }
}
