import Foundation

/// Typed value used to construct arbitrary Directory Record keys without
/// exposing the writer's mutable Data Element graph.
public indirect enum DICOMDirectoryValue {
    case string(String)
    case data(Data)
    case int16(Int16)
    case int32(Int32)
    case int64(Int64)
    case uint16(UInt16)
    case uint32(UInt32)
    case uint64(UInt64)
    case float32(Float32)
    case float64(Float64)
    case int16Values([Int16])
    case int32Values([Int32])
    case int64Values([Int64])
    case uint16Values([UInt16])
    case uint32Values([UInt32])
    case uint64Values([UInt64])
    case float32Values([Float32])
    case float64Values([Float64])
    case attributeTags([DataTag])
    case sequence([[String:DICOMDirectoryValue]])
}

/// Declarative Directory Record tree used by the generic DICOMDIR writer.
///
/// Element dictionary keys are DICOM keywords. Offset, in-use, and record-type
/// elements are generated by the writer and shall not be supplied here.
public struct DICOMDirectoryRecordDefinition {
    public var type:DICOMDirectoryRecordType
    public var elements:[String:DICOMDirectoryValue]
    public var children:[DICOMDirectoryRecordDefinition]

    public init(
        type:DICOMDirectoryRecordType,
        elements:[String:DICOMDirectoryValue] = [:],
        children:[DICOMDirectoryRecordDefinition] = []
    ) {
        self.type = type
        self.elements = elements
        self.children = children
    }
}
