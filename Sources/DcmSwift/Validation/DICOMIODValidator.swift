import Foundation

/// A condition of PS3.3 that tests attributes, such as "Required if Image
/// Type (0008,0008) Value 1 is ORIGINAL or MIXED", as the generator reads it.
public struct DICOMIODCondition: Sendable, Equatable {
    public enum Test: String, Sendable {
        case present, absent, hasValue, empty, nonzero, equals, notEquals, greater, absentOrEquals, absentOrEmpty
    }

    public struct Term: Sendable, Equatable {
        /// The tag as 8 uppercase hexadecimal digits.
        public let tag: String
        public let test: Test
        public let values: [String]
        /// The index of the Value tested, from 0.
        public let index: Int
    }

    /// Whether every term must hold, or one is enough.
    public let requiresAll: Bool
    public let terms: [Term]

    init?(json: Any?) {
        guard let object = json as? [String: Any],
              let list = (object["all"] ?? object["any"]) as? [[String: Any]] else { return nil }
        let terms = list.compactMap { term -> Term? in
            guard let tag = term["tag"] as? String, let test = (term["test"] as? String).flatMap(Test.init) else {
                return nil
            }
            return Term(tag: tag, test: test, values: term["values"] as? [String] ?? [], index: term["index"] as? Int ?? 0)
        }
        guard !terms.isEmpty, terms.count == list.count else { return nil }
        requiresAll = object["all"] != nil
        self.terms = terms
    }
}

/// The IODs, modules, and macros of PS3.3 2026d, and the IOD of each SOP
/// Class (PS3.4), generated by Scripts/generate-dicom-iods.py.
public final class DICOMIODSpecification: @unchecked Sendable {
    /// One row of an attribute table: an attribute, or an included table.
    public struct Entry: Sendable {
        public let depth: Int
        /// The tag as 8 uppercase hexadecimal digits, possibly with "X" for
        /// repeating groups; nil for an inclusion.
        public let tag: String?
        /// The Attribute Type: 1, 1C, 2, 2C, or 3.
        public let type: String?
        public let enumeratedValues: [String]?
        /// The condition sentence of Types 1C and 2C.
        public let condition: String?
        /// The included table, for an "Include" row.
        public let include: String?
        /// The Baseline or Defined Context Group of an included code macro.
        public let contextGroup: Int?
        /// The condition of a conditional inclusion.
        public let includeCondition: String?
        /// The condition of the Type or of the inclusion, when it tests
        /// attributes.
        public let when: DICOMIODCondition?
    }

    public struct Table: Sendable {
        public let id: String
        public let name: String
        public let entries: [Entry]
    }

    public struct ModuleReference: Sendable {
        public let name: String
        /// The module or macro table, such as C.7-1.
        public let table: String?
        /// M, C, or U.
        public let usage: String
        public let condition: String?
        /// The condition, when it tests attributes.
        public let when: DICOMIODCondition?
    }

    public struct IOD: Sendable {
        /// The PS3.3 section of the module table, such as A.3.3.
        public let id: String
        public let name: String
        public let modules: [ModuleReference]
        /// The Functional Group Macros of an enhanced multi-frame IOD.
        public let functionalGroups: [ModuleReference]
    }

    public static let shared: DICOMIODSpecification = {
        do {
            guard let url = Bundle.module.url(forResource: "dicom-iods-2026d", withExtension: "json") else {
                throw DICOMIODValidationError("the IOD resource is missing")
            }
            return try DICOMIODSpecification(data: Data(contentsOf: url))
        } catch {
            fatalError("DcmSwift's bundled IOD specification cannot be read: \(error)")
        }
    }()

    public let edition: String
    private let sopClasses: [String: String]
    private let iods: [String: IOD]
    private let tables: [String: Table]

    public init(data: Data) throws {
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
            throw DICOMIODValidationError("the IOD specification is not a JSON object")
        }
        edition = root["edition"] as? String ?? ""
        sopClasses = root["sopClasses"] as? [String: String] ?? [:]
        func references(_ list: Any?) -> [ModuleReference] {
            (list as? [[String: Any]] ?? []).map {
                ModuleReference(name: $0["name"] as? String ?? "", table: $0["table"] as? String,
                                usage: $0["usage"] as? String ?? "U", condition: $0["condition"] as? String,
                                when: DICOMIODCondition(json: $0["when"]))
            }
        }
        var iods: [String: IOD] = [:]
        for (id, value) in root["iods"] as? [String: [String: Any]] ?? [:] {
            iods[id] = IOD(id: id, name: value["name"] as? String ?? "", modules: references(value["modules"]),
                           functionalGroups: references(value["functionalGroups"]))
        }
        self.iods = iods
        var tables: [String: Table] = [:]
        for (id, value) in root["tables"] as? [String: [String: Any]] ?? [:] {
            let entries = (value["entries"] as? [[String: Any]] ?? []).map {
                Entry(depth: $0["depth"] as? Int ?? 0, tag: $0["tag"] as? String, type: $0["type"] as? String,
                      enumeratedValues: $0["enumerated"] as? [String],
                      condition: $0["include"] == nil ? $0["condition"] as? String : nil,
                      include: $0["include"] as? String, contextGroup: $0["cid"] as? Int,
                      includeCondition: $0["include"] != nil ? $0["condition"] as? String : nil,
                      when: DICOMIODCondition(json: $0["when"]))
            }
            tables[id] = Table(id: id, name: value["name"] as? String ?? "", entries: entries)
        }
        self.tables = tables
    }

    /// The IOD of a SOP Class.
    public func iod(forSOPClass uid: String) -> IOD? { sopClasses[uid].flatMap { iods[$0] } }
    public func table(_ id: String) -> Table? { tables[id] }
    public var sopClassUIDs: [String] { sopClasses.keys.sorted() }

    /// An attribute of a table with its nested attributes, macros expanded.
    final class Node {
        let tag: String
        let type: String
        let enumeratedValues: [String]?
        /// The condition of Type 1C or 2C, when it tests attributes.
        let when: DICOMIODCondition?
        let table: String
        var children: [Node] = []
        /// The condition of the inclusion that brought this attribute, as
        /// "if and only if Value Type (0040,A040) is NUM"; `nil` when the
        /// inclusion is unconditional, and unknown when it does not test
        /// attributes.
        var inclusion: Inclusion = .unconditional

        enum Inclusion {
            case unconditional
            case when(DICOMIODCondition)
            case unknown
        }

        init(tag: String, type: String, enumeratedValues: [String]?, when: DICOMIODCondition?, table: String) {
            self.tag = tag
            self.type = type
            self.enumeratedValues = enumeratedValues
            self.when = when
            self.table = table
        }
    }

    private let lock = NSLock()
    private var expanded: [String: [Node]] = [:]

    /// The attributes of a table as a tree, with included tables expanded.
    func tree(_ id: String) -> [Node] {
        lock.lock()
        if let cached = expanded[id] { lock.unlock(); return cached }
        lock.unlock()
        var visiting = Set<String>()
        let nodes = build(id, visiting: &visiting)
        lock.lock()
        expanded[id] = nodes
        lock.unlock()
        return nodes
    }

    private func build(_ id: String, visiting: inout Set<String>) -> [Node] {
        guard let table = tables[id], visiting.insert(id).inserted else { return [] }
        defer { visiting.remove(id) }
        var roots: [Node] = []
        // The latest node at each depth, to attach deeper rows to.
        var stack: [Node] = []
        func attach(_ nodes: [Node], depth: Int) {
            if depth == 0 {
                roots += nodes
            } else if depth - 1 < stack.count {
                stack[depth - 1].children += nodes
            }
        }
        for entry in table.entries {
            stack = Array(stack.prefix(entry.depth))
            if let include = entry.include {
                let included = build(include, visiting: &visiting)
                if entry.includeCondition != nil {
                    let inclusion: Node.Inclusion = entry.when.map { .when($0) } ?? .unknown
                    for node in included { node.inclusion = inclusion }
                }
                attach(included, depth: entry.depth)
                continue
            }
            guard let tag = entry.tag, let type = entry.type else { continue }
            let node = Node(tag: tag, type: type, enumeratedValues: entry.enumeratedValues, when: entry.when, table: id)
            attach([node], depth: entry.depth)
            stack.append(node)
        }
        return roots
    }
}

public struct DICOMIODValidationError: Error, CustomStringConvertible {
    public let description: String
    init(_ description: String) { self.description = description }
}

/// A problem found in a data set against its IOD.
public struct DICOMIODFinding: Equatable, Sendable, CustomStringConvertible {
    public enum Kind: String, Equatable, Sendable {
        /// A Type 1 or 2 attribute is absent.
        case missing
        /// A Type 1 or 1C attribute is present without a value.
        case empty
        /// A value is not among the Enumerated Values.
        case unexpectedValue
        /// The data set has no SOP Class UID, or its SOP Class has no IOD.
        case unknownIOD
    }

    public let kind: Kind
    /// The tags from the top-level attribute to the attribute, such as
    /// ["00081115", "0020000E"], each as 8 hexadecimal digits.
    public let path: [String]
    /// The module or Functional Group Macro, such as "Patient".
    public let module: String
    /// The PS3.3 table that defines the attribute, such as C.7-1.
    public let table: String
    public let message: String

    public var description: String {
        let location = path.map { "(\($0.prefix(4)),\($0.suffix(4)))" }.joined(separator: " > ")
        return "\(module): \(location) \(message) [PS3.3 Table \(table)]"
    }
}

/// The result of validating a data set against its IOD.
public struct DICOMIODValidationReport: Sendable {
    public let sopClassUID: String?
    /// The IOD, such as "CT Image IOD Modules"; nil when unknown.
    public let iod: String?
    /// The modules checked: mandatory ones, and the others present.
    public let checkedModules: [String]
    public let findings: [DICOMIODFinding]

    public var isValid: Bool { findings.isEmpty }
}

/// Validates data sets against the IODs of PS3.3: Attribute Types, nested
/// Sequence Items, included macros, Enumerated Values, and the Functional
/// Group Macros of enhanced multi-frame IODs.
///
/// This is a layer separate from parsing: a file that does not conform is
/// still read. Mandatory modules are always checked; user-optional and
/// conditional modules are checked when one of their attributes is present,
/// and conditional modules also when their condition holds. The conditions
/// of Types 1C and 2C, of modules, and of inclusions are evaluated when they
/// test attributes, such as "Required if Image Type (0008,0008) Value 1 is
/// ORIGINAL"; the others, such as "Required if contrast media was used", are
/// not: such an attribute is checked only when present.
public struct DICOMIODValidator: Sendable {
    public let specification: DICOMIODSpecification

    public init(specification: DICOMIODSpecification = .shared) {
        self.specification = specification
    }

    public func validate(_ dataSet: DataSet) -> DICOMIODValidationReport {
        let root = Container(elements: dataSet.allElements.filter { $0.group != "0002" })
        guard let sopClass = root.string("00080016") else {
            return DICOMIODValidationReport(sopClassUID: nil, iod: nil, checkedModules: [], findings: [
                DICOMIODFinding(kind: .unknownIOD, path: ["00080016"], module: "SOP Common", table: "C.12-1",
                                message: "SOP Class UID is missing, so the IOD is unknown"),
            ])
        }
        guard let iod = specification.iod(forSOPClass: sopClass) else {
            return DICOMIODValidationReport(sopClassUID: sopClass, iod: nil, checkedModules: [], findings: [
                DICOMIODFinding(kind: .unknownIOD, path: ["00080016"], module: "SOP Common", table: "C.12-1",
                                message: "SOP Class \(sopClass) has no IOD in PS3.3 \(specification.edition)"),
            ])
        }
        var findings: [DICOMIODFinding] = []
        var checked: [String] = []
        // Attributes of mandatory modules do not make an optional module
        // present: SOP Common and others share some.
        let mandatoryTags = Set(iod.modules.filter { $0.usage == "M" }.compactMap(\.table)
            .flatMap { specification.tree($0).map(\.tag) })
        for module in iod.modules {
            guard let table = module.table else { continue }
            let nodes = specification.tree(table)
            if module.usage != "M" {
                let own = nodes.filter { !mandatoryTags.contains($0.tag) }
                let present = own.contains { root.element($0.tag) != nil }
                let required = module.usage == "C" && module.when.map { Container.evaluate($0, in: root, root: root) } == true
                guard present || required else { continue }
            }
            checked.append(module.name)
            check(nodes, in: root, root: root, path: [], module: module.name, into: &findings)
        }
        if !iod.functionalGroups.isEmpty {
            checkFunctionalGroups(iod.functionalGroups, root: root, into: &findings, checked: &checked)
        }
        // One attribute may be required by several modules: report it once.
        var seen = Set<String>()
        findings = findings.filter { seen.insert("\($0.kind)|\($0.path)").inserted }
        return DICOMIODValidationReport(sopClassUID: sopClass, iod: iod.name, checkedModules: checked, findings: findings)
    }

    // MARK: Attributes

    private func check(_ nodes: [DICOMIODSpecification.Node], in container: Container, root: Container,
                       path: [String], module: String, into findings: inout [DICOMIODFinding]) {
        for node in nodes where !node.tag.contains("X") {
            // A conditional inclusion is checked only when its condition is
            // known to hold.
            switch node.inclusion {
            case .unconditional: break
            case .unknown: continue
            case .when(let condition):
                guard Container.evaluate(condition, in: container, root: root) else { continue }
            }
            let location = path + [node.tag]
            let element = container.element(node.tag)
            let required: Bool
            switch node.type {
            case "1", "2": required = true
            case "1C", "2C": required = node.when.map { Container.evaluate($0, in: container, root: root) } ?? false
            default: required = false
            }
            if required && element == nil {
                let reason = node.type.hasSuffix("C") ? ", required by its condition" : ""
                findings.append(DICOMIODFinding(kind: .missing, path: location, module: module, table: node.table,
                                                message: "is missing (Type \(node.type)\(reason))"))
                continue
            }
            guard let element else { continue }
            if (node.type == "1" || node.type == "1C") && Container.isEmpty(element) {
                findings.append(DICOMIODFinding(kind: .empty, path: location, module: module, table: node.table,
                                                message: "is empty (Type \(node.type))"))
                continue
            }
            if let enumerated = node.enumeratedValues, !Container.isEmpty(element),
               DicomSpec.shared.vmForTag(withCode: node.tag.lowercased()) == "1",
               let value = Container.strings(element).first, !Container.matches(value, enumerated) {
                findings.append(DICOMIODFinding(
                    kind: .unexpectedValue, path: location, module: module, table: node.table,
                    message: "has the value \"\(value)\", not one of the Enumerated Values \(enumerated.joined(separator: ", "))"))
            }
            if let sequence = element as? DataSequence, !node.children.isEmpty {
                for item in sequence.items {
                    check(node.children, in: Container(elements: item.elements), root: root, path: location,
                          module: module, into: &findings)
                }
            }
        }
    }

    // MARK: Functional Groups (PS3.3 C.7.6.16)

    private func checkFunctionalGroups(
        _ macros: [DICOMIODSpecification.ModuleReference], root: Container, into findings: inout [DICOMIODFinding],
        checked: inout [String]
    ) {
        let shared = (root.element("52009229") as? DataSequence)?.items.first.map { Container(elements: $0.elements) }
        let perFrame = ((root.element("52009230") as? DataSequence)?.items ?? []).map { Container(elements: $0.elements) }
        for macro in macros {
            guard let table = macro.table else { continue }
            let nodes = specification.tree(table)
            // A Functional Group Macro is one Sequence, in the Shared
            // Functional Groups or in every frame's.
            guard let group = nodes.first, nodes.count == 1 else { continue }
            let inShared = shared?.element(group.tag) != nil
            let inFrames = !perFrame.isEmpty && perFrame.allSatisfy { $0.element(group.tag) != nil }
            let required = macro.usage == "M"
                || (macro.usage == "C" && macro.when.map { Container.evaluate($0, in: root, root: root) } == true)
            if inShared || inFrames {
                checked.append(macro.name)
                if let shared, inShared {
                    check(nodes, in: shared, root: root, path: ["52009229"], module: macro.name, into: &findings)
                } else {
                    for frame in perFrame {
                        check(nodes, in: frame, root: root, path: ["52009230"], module: macro.name, into: &findings)
                    }
                }
            } else if required {
                findings.append(DICOMIODFinding(
                    kind: .missing, path: [group.tag], module: macro.name, table: table,
                    message: "is in neither the Shared nor every Per-Frame Functional Groups Sequence Item"))
            }
        }
    }
}

/// The attributes of a data set or an Item, by tag.
private struct Container {
    let byTag: [String: DataElement]

    init(elements: [DataElement]) {
        var byTag: [String: DataElement] = [:]
        for element in elements { byTag[element.tagCode().uppercased()] = element }
        self.byTag = byTag
    }

    func element(_ tag: String) -> DataElement? { byTag[tag] }

    func string(_ tag: String) -> String? {
        guard let element = byTag[tag] else { return nil }
        return Container.strings(element).first
    }

    /// A Sequence without Items, a Value Field of zero length, or text made
    /// only of padding. Encapsulated Pixel Data has fragments, not Items.
    static func isEmpty(_ element: DataElement) -> Bool {
        if element is PixelSequence { return false }
        if let sequence = element as? DataSequence { return sequence.items.isEmpty }
        guard let data = element.data, !data.isEmpty else { return true }
        if let text = element.textValues { return text.allSatisfy { trim($0).isEmpty } }
        return false
    }

    /// The Values as text: character strings trimmed of padding, and
    /// binary numbers in decimal.
    static func strings(_ element: DataElement) -> [String] {
        if element.vr == .UN, let data = element.data, !data.isEmpty { return unknownVRStrings(element, data) }
        if let text = element.textValues { return text.map(trim) }
        if let values = element.uint16Values { return values.map { String($0) } }
        if let values = element.int16Values { return values.map { String($0) } }
        if let values = element.uint32Values { return values.map { String($0) } }
        if let values = element.int32Values { return values.map { String($0) } }
        return []
    }

    /// Whether a condition holds. Each attribute is looked up in the data
    /// set or Item being checked, then at the top level of the data set.
    static func evaluate(_ condition: DICOMIODCondition, in container: Container, root: Container) -> Bool {
        let results = condition.terms.map { term -> Bool in
            let element = container.element(term.tag) ?? root.element(term.tag)
            let values = element.map(strings) ?? []
            let value = term.index < values.count ? values[term.index] : nil
            switch term.test {
            case .present: return element != nil
            case .absent: return element == nil
            case .hasValue: return element.map { !isEmpty($0) } ?? false
            case .empty: return element.map(isEmpty) ?? false
            case .nonzero:
                guard let element, !isEmpty(element) else { return false }
                return value.map { Double($0) != 0 } ?? true
            case .equals: return value.map { matches($0, term.values) } ?? false
            case .notEquals: return value.map { !matches($0, term.values) } ?? false
            case .greater:
                guard let value = value.flatMap(Double.init), let limit = term.values.first.flatMap(Double.init) else {
                    return false
                }
                return value > limit
            case .absentOrEquals: return element == nil || value.map { matches($0, term.values) } == true
            case .absentOrEmpty: return element.map(isEmpty) ?? true
            }
        }
        return condition.requiresAll ? results.allSatisfy { $0 } : results.contains(true)
    }

    /// The Values of an element written with VR UN, read with its VR in the
    /// Data Dictionary: UN Values are Little Endian (PS3.5 6.2.2).
    private static func unknownVRStrings(_ element: DataElement, _ data: Data) -> [String] {
        let bytes = [UInt8](data)
        func numbers(_ width: Int, _ signed: Bool) -> [String] {
            guard bytes.count.isMultiple(of: width) else { return [] }
            return stride(from: 0, to: bytes.count, by: width).map { offset in
                let value = (0..<width).reduce(UInt64(0)) { $0 | UInt64(bytes[offset + $1]) << (8 * UInt64($1)) }
                if !signed { return String(value) }
                return width == 2 ? String(Int16(truncatingIfNeeded: value)) : String(Int32(truncatingIfNeeded: value))
            }
        }
        switch DicomSpec.shared.vrForTag(withCode: element.tagCode()) {
        case .US?: return numbers(2, false)
        case .SS?: return numbers(2, true)
        case .UL?: return numbers(4, false)
        case .SL?: return numbers(4, true)
        case .AE?, .AS?, .CS?, .DA?, .DS?, .DT?, .IS?, .LO?, .PN?, .SH?, .TM?, .UI?, .UC?:
            return String(decoding: bytes, as: UTF8.self).split(separator: "\\", omittingEmptySubsequences: false)
                .map { trim(String($0)) }
        case .LT?, .ST?, .UT?, .UR?:
            return [trim(String(decoding: bytes, as: UTF8.self))]
        default:
            return []
        }
    }

    /// Whether a Value is one of the Enumerated Values. PS3.3 writes those
    /// of binary attributes in hexadecimal, such as 0001H.
    static func matches(_ value: String, _ enumerated: [String]) -> Bool {
        enumerated.contains { term in
            if term == value { return true }
            if let number = Int(term), Int(value) == number { return true }
            guard term.hasSuffix("H"), let number = Int(term.dropLast(), radix: 16) else { return false }
            return Int(value) == number
        }
    }

    private static func trim(_ value: String) -> String {
        value.trimmingCharacters(in: CharacterSet(charactersIn: " \0"))
    }
}

/// What a receiver does with an instance that does not conform to its IOD.
public enum DICOMIODValidationPolicy: String, CaseIterable, Sendable {
    /// Store every instance without validating it.
    case off
    /// Store the instance, and answer with the warning "Data Set does not
    /// match SOP Class" (C-STORE Status B007, STOW-RS Warning Reason B007).
    case warn
    /// Refuse the instance with the failure "Data Set does not match SOP
    /// Class" (C-STORE Status A900, STOW-RS Failure Reason A900).
    case reject

    /// The validation report of a received instance, or nil when the policy
    /// is off. An instance whose SOP Class has no IOD in PS3.3, such as a
    /// retired or private one, is not reported: nothing says how it should
    /// look.
    public func report(
        for instance: DICOMReceivedInstance, validator: DICOMIODValidator = DICOMIODValidator()
    ) -> DICOMIODValidationReport? {
        guard self != .off else { return nil }
        guard let dataSet = try? instance.dataSet() else { return nil }
        let report = validator.validate(dataSet)
        guard !report.findings.contains(where: { $0.kind == .unknownIOD }), !report.isValid else { return nil }
        return report
    }
}
